const dictionaries: Record<Lang, Record<string, string>> = { de, en };

export function t(key: string, vars?: Record<string, string | number>): string {
    const text = dictionaries[lang.current][key] ?? dictionaries.de[key] ?? key;
    if (vars == null) {
        return text;
    }
    return text.replace(/\{(\w+)\}/g, (_, name) => (vars[name] != null ? String(vars[name]) : `{${name}}`));
}

export function locale(): string {
    return lang.current === 'de' ? 'de-DE' : 'en-GB';
}
